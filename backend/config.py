"""
config.py – Central configuration for CultureLens.

All tuneable thresholds, paths and constants live here so they are
easy to find, adjust during a demo, and explain in a viva.
"""

from pathlib import Path

# ── Project paths (relative to repo root) ──────────────────────────
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = PROJECT_ROOT / "data"
MODELS_DIR = PROJECT_ROOT / "models"
FRONTEND_DIR = PROJECT_ROOT / "frontend"

PHRASES_PATH = DATA_DIR / "phrases.json"
CULTURES_PATH = DATA_DIR / "cultures.json"
TRAINING_DATA_PATH = DATA_DIR / "training_data.csv"
