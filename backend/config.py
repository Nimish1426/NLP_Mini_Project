CLASSIFIER_PATH = MODELS_DIR / "classifier.joblib"
PHRASE_EMBEDDINGS_PATH = MODELS_DIR / "phrase_embeddings.npy"

# ── Input validation ───────────────────────────────────────────────
MAX_INPUT_LENGTH = 5000          # characters
MIN_INPUT_LENGTH = 1             # reject empty strings

# ── Layer 1: Rule-based detector ───────────────────────────────────
RULE_CONFIDENCE = 0.95           # rules are high-confidence by design

# ── Layer 2: Semantic detector ─────────────────────────────────────
SEMANTIC_THRESHOLD = 0.62        # cosine-sim cutoff for flagging
SEMANTIC_MODEL_NAME = "all-MiniLM-L6-v2"  # ~80 MB, CPU-friendly
MAX_CHUNKS_PER_SENTENCE = 40     # upper bound on n-gram candidates
SEMANTIC_NGRAM_MIN = 3           # minimum tokens in a chunk
SEMANTIC_NGRAM_MAX = 6           # maximum tokens in a chunk

# ── Layer 3: ML classifier ────────────────────────────────────────
ML_CONFIDENCE_THRESHOLD = 0.60   # min predicted probability to flag
ML_RANDOM_SEED = 42              # reproducibility

# ── Tone analyzer ─────────────────────────────────────────────────
TONE_MISMATCH_THRESHOLD = 0.35   # difference to trigger a tone flag

# ── Scorer ─────────────────────────────────────────────────────────
# score = min(100, 100 * (1 - exp(-k * Σ(sev_i * conf_i / √N))))
SCORER_K = 0.25                  # scaling constant

# Severity cut-offs for adjusted_risk → severity level
SEVERITY_LOW_MAX = 1.5           # adjusted_risk ≤ this → severity 1
SEVERITY_MED_MAX = 2.5           # adjusted_risk ≤ this → severity 2
                                  # above → severity 3

